<h2 id="sending">{t().guides.sections.sending}</h2>

<h3>Flickでできること</h3>
<p>一時的なパスワード、Wi-Fiのパスワード、APIトークン、契約書、ログファイルなど、大切な内容を1回だけ渡したいときに使います。相手が一度開くか有効時間が過ぎると、サーバーから消去されます。送る前にブラウザで内容をロックし、鍵はサーバーへ送らないため、公開されているコードどおりに動いている限り運営者も内容を読めません。仕組みと限界は<a href="#privacy">開発者向けの説明</a>にまとめています。</p>

<h3>リンクを作って送る手順</h3>
<ol>
	<li>送る内容を選びます。<strong>メモ</strong>、<strong>ファイル</strong>（複数ファイルやフォルダーは1つに圧縮されます）、または<strong>ログイン</strong>・<strong>カード</strong>・<strong>個人情報</strong>・<strong>カスタム</strong>のテンプレートを選べます。</li>
	<li><strong>有効時間</strong>を決めます。10分、1時間、24時間、7日から選ぶか、5分から7日の間で指定してください。</li>
	<li>必要に応じて<strong>パスワードをかける</strong>をオンにします。</li>
	<li><strong>リンクを作成</strong>を押し、できたリンクを丸ごと相手に送ります。<code>#</code>より後ろが内容を開く鍵になるため、途中で切れたリンクは開けません。</li>
</ol>

<h3>LINEや社内チャットなど、他の人も見られる場所に貼るときは？</h3>
<p><strong>パスワードをかける</strong>を使ってください。パスワードをかけると、リンクだけでは開けなくなります。パスワードは電話や別のチャットなど、リンクとは別の経路で伝えてください。パスワードを5回間違えると、そのリンクはロックされて二度と開けなくなります。</p>

<h3>相手と通話中や、すぐそばにいるときは？</h3>
<p>リンクの代わりに<strong>リアルタイム転送</strong>が使えます。双方の画面が開いている間に内容を直接やり取りでき、データベースやファイルストレージには何も保存されません。送る側に表示された6桁のコードを、受け取る人が3分以内に<strong>コード入力</strong>へ入力します。双方の画面に出た3桁の確認番号を口頭などで照合し、送る側が正しい端末を選べば転送が完了します。</p>

<h3>受け取ったリンクを開くとどうなりますか？</h3>
<p>リンクを開くと、まず<strong>内容を開く</strong>ボタンがある画面が表示されます。この画面を開いただけでは内容は消えません。<strong>内容を開く</strong>を押した時点で内容が1回だけ表示され、サーバーから削除されます。ページを再読み込みすると二度と見られないため、受け取った人はすぐにコピーするか保存してください。</p>

<h3>リンクが開けないときは？</h3>
<p><code>#</code>以降が欠けたリンクは開けません。誰も開かないまま<strong>有効時間</strong>が過ぎた場合も、自動で削除されます。初めて開くリンクなのに<strong>この内容はもう開けません。</strong>と表示された場合は、期限切れか取り消し、または第三者が先に開いたかのいずれかです。先に見られた可能性があるため送った人に知らせ、内容が漏れたものとしてパスワードなどを変更してもらってください。</p>

<h3>相手からパスワードやファイルを受け取りたいときは？</h3>
<p><a href={resolve('/request')}>リンクでリクエスト</a>を使うと、リンクが2つ作られます。相手には<strong>相手に渡すリンク</strong>を渡し、メモ・ファイル・ログイン情報などを1回送ってもらいます。届いた内容は、手元に残した<strong>自分用の受け取りリンク</strong>から1回だけ開けます。複数回送られても、最初に届いた1件だけが有効になります。</p>

<h3>送ったリンクを途中で取り消せますか？</h3>
<p>相手がまだ開く前であれば、作成時に表示された<strong>自分用の管理リンク</strong>からいつでも取り消せます。</p>

<h2 id="limits">{t().guides.sections.limits}</h2>
<p>サーバーからデータを消すことはできても、次の点までは防げません。</p>
<ul>
	<li><strong>一度見られた内容は取り消せません：</strong>受け取る人が内容をコピーしたり、スクリーンショットを撮ったり、ファイルを保存したりすると戻せません。一時パスワードなどは使い終わったら変更してください。</li>
	<li><strong>開いた人の特定や、感染済み端末の保護はできません：</strong>リンク全体を持っていれば誰でも1回開けるため、誰が開いたかは証明できません。すでにウイルスなどに感染した端末上の情報も守れません。</li>
	<li><strong>手元にコピーが残ることがあります：</strong>チャットの履歴、クリップボード、ブラウザの閲覧履歴にリンクや内容が残る場合があります。</li>
	<li><strong>信頼できるサーバーを選んでください：</strong>内容をロックするコードは接続先のFlickサーバーから配信されます。運営者を信頼できるインスタンスを使うか、<a href="#self-host">自分で運用</a>してください。</li>
</ul>

