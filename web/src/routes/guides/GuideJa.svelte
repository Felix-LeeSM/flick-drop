<h2 id="sending">{t().guides.sections.sending}</h2>

<h3>Flickは何に使うものですか？</h3>
<p>大切な情報を1回だけ渡すときに使います。一時的なパスワード、Wi-Fiのパスワード、APIトークン、契約書、ログファイルなどです。1回開くと使えなくなるリンクが作成されます。Flickはパスワード管理ツールやファイル保管庫ではありません。受け渡しが終わると何も残りません。</p>

<h3>Flickの運営者は送った内容を読めますか？</h3>
<p>Flickが公開しているコードでは読めません。内容は端末から送られる前にブラウザで暗号化され、内容を開くための鍵はサーバーに届きません。サーバーに保存されるのは、サーバー自身も開けない暗号化されたデータだけです。仕組みと、この約束がどこまで及ぶかは<a href="#privacy">開発者向けの説明</a>にあります。</p>

<h3>どうやって送りますか？</h3>
<ol>
	<li>送るものを選びます。<strong>メモ</strong>、<strong>ファイル</strong>（複数のファイルやフォルダーは1つにまとめて圧縮されます）、または<strong>ログイン</strong>、<strong>カード</strong>、<strong>個人情報</strong>、<strong>カスタム</strong>のテンプレートから選べます。</li>
	<li>待つ時間を決めます。10分、1時間、24時間、7日から選ぶか、5分から7日の間で指定できます。</li>
	<li>必要に応じてパスワードをかけます。</li>
	<li><strong>リンクを作成</strong>を押し、リンク全体を受け取る人に送ります。<code>#</code>より後ろの部分が鍵なので、途中で切れたリンクは開けません。</li>
</ol>

<h3>受け取る人には何が表示されますか？</h3>
<p>リンクを開くと、<strong>内容を開く</strong>ボタンのあるページが表示されます。このページを読み込むだけではリンクは使われません。<strong>内容を開く</strong>を押すと内容が1回だけ表示され、サーバーから削除されます。その後に再読み込みすると、もう開けないと表示されます。受け取る人は必要な内容をすぐにコピーするか保存してください。</p>

<h3>誰も開かなかった場合は？</h3>
<p>有効時間が過ぎると削除されます。どちらの場合も、リンクを開けるのは多くても1回です。</p>

<h3>パスワードはどんなときにかけますか？</h3>
<p>他の人にリンクを見られるおそれがあるときです。たとえば、複数人が参加するチャットで送る場合です。パスワードをかけると、リンクだけでは開けません。パスワードは電話や別のメッセンジャーなど、別の方法で伝えてください。パスワードを5回間違えると、二度と開けないようにロックされます。</p>

<h3>リアルタイム転送とは何ですか？</h3>
<p><strong>リアルタイム転送</strong>は、両方の端末が開いている間に内容を送る方法です。送る人には6桁のコードが表示され、受け取る人は3分以内にそのコードを<strong>コード入力</strong>に入力します。待機中の端末には、それぞれ3桁の確認番号が表示されます。受け取る人がその番号を読み上げ、送る人が正しい端末を選びます。データベースやファイルストレージには何も書き込まれません。内容は転送している間だけサーバーを通過します。</p>

<h3>相手から送ってもらうこともできますか？</h3>
<p>できます。<a href={resolve('/request')}>リンクでリクエスト</a>を使うと、リンクが2つ作成されます。相手は<strong>相手に渡すリンク</strong>からメモ・ファイル・認証情報を送り、自分は自分だけで保管する<strong>自分用の受け取りリンク</strong>で、届いた内容を1回だけ開きます。複数回送られた場合は、最初に送られた内容だけが届きます。</p>

<h3>リンクが漏れたらどうなりますか？</h3>
<p>リンク全体を知っている人なら誰でも1回だけ開けます。受け取る人が開こうとしたときにすでに開かれていた場合は、内容が漏れたものとして変更してください。送る人は、まだ開かれていないリンクを<strong>自分用の管理リンク</strong>からキャンセルすることもできます。</p>

<h2 id="limits">{t().guides.sections.limits}</h2>
<p>Flickは、受け取る人がすでに見た内容を取り消せません。受け取る人は内容をコピーしたり、スクリーンショットを撮ったり、ファイルを保存したりできます。1回だけ開けるリンクで送っても、中のパスワードが使い捨てになるわけではありません。一時的に渡したログイン情報は、用が済んだら変更してください。</p>
<p>また、Flickは誰がリンクを開いたかを証明できず、すでに乗っ取られた端末にある内容は守れません。内容を暗号化するページは、利用中のFlickサーバーから配信されます。運営者を信頼できるサーバーを使うか、<a href="#self-host">自分で運用</a>してください。チャットの履歴、クリップボード、ブラウザの閲覧履歴にコピーが残ることもあります。</p>

