<h2 id="privacy">{t().guides.sections.privacy}</h2>
<p>内容は、公開されたファイル暗号化形式である<a href="https://age-encryption.org/">age</a>を使ってブラウザで暗号化されます。送るたびに新しく生成する耐量子ハイブリッド鍵（ML-KEM-768とX25519）を使います。大きなファイルは64 KiBのチャンクに分けて暗号化され、最後のチャンクの検証が済むまで何も表示されません。</p>
<p>パスワードがない場合、鍵はリンクのフラグメント（<code>#</code>以降の部分）である<code>#key=AGE-SECRET-KEY-PQ-1…</code>に入ります。ブラウザはフラグメントをサーバーに送らないため、サーバーへの通信やアクセスログには残りません。</p>
<p>パスワードをかけると、鍵はageのscryptモード（work factor 18）で包まれ、包んだ鍵だけがアップロードされます。パスワードからは別のアクセス証明（PBKDF2-SHA-256、600,000回反復）も作られます。サーバーはその証明のハッシュだけを保存し、内容を渡す前に照合します。データベースのコピーを持つ人は、包まれた鍵に対してオフラインでパスワードを推測し続けられるため、長いパスワードを使ってください。パスワードの生成機能は80ビットのパスワードを作ります。</p>
<p>サーバーが保存するのは、ID、暗号化されたデータ、そのサイズ、ファイルの種類、暗号化されたファイル名、日時、パスワードを間違えた回数です。IPアドレスは保存しません。Webのアクセスログでは、リンクのIDを<code>&lt;id&gt;</code>に置き換え、クライアントのIP、リファラー、クエリ文字列は記録しません。</p>
<p>リアルタイム転送は仕組みが異なります。受け取る人のブラウザが1回限りの鍵ペアを作り、公開鍵だけを送ります。送る人はその公開鍵で暗号化し、サーバーは暗号文をメモリ上で中継します。コードのハッシュや端末の表示名などの待機中の情報は、永続化しないキャッシュに短時間だけ置かれます。</p>
<aside>
	<p><strong>あらゆるWeb暗号化に共通する限界：</strong>サーバーが送るJavaScriptを信頼する必要があります。悪意を持ったサーバーなら、鍵やパスワードを盗むコードを配信できます。リアルタイム転送では、自分の鍵にすり替えることもできます。この設計が守るのはデータベース、ログ、バックアップの流出であり、運営者が悪意を持った場合までは守れません。<code>SHA256SUMS</code>で検証したコマンドラインクライアントを使えば、配信されるコードを信頼する必要はなくなります。</p>
</aside>

<h2 id="source">{t().guides.sections.source}</h2>
<p>FlickはApache 2.0ライセンスのオープンソースです。リポジトリは<a href={repo}>github.com/Felix-LeeSM/flick-drop</a>です。最初に読むなら、次の場所がおすすめです。</p>
<ul>
	<li><code>web/src/lib/crypto/</code>：ブラウザでの暗号化、リンクの鍵、パスワードのアクセス証明。</li>
	<li><code>contracts/age-format-v1.md</code>：暗号化形式と、API呼び出しごとに送られるデータ。</li>
	<li><code>docs/architecture/security-model.md</code>：対象外の範囲も含めた脅威モデル全体。</li>
	<li><code>cmd/flick</code>：ブラウザと同じ方法で暗号化するコマンドラインクライアント。</li>
</ul>
<p>コマンドラインクライアントを使うと、ターミナルから送ったり開いたりできます。</p>
<pre><code>go install github.com/Felix-LeeSM/flick-drop/cmd/flick@latest
flick send -ttl 1h -file report.pdf
flick open 'https://flick.example/s/…#key=…'</code></pre>
<p>macOS、Linux、Windows向けのリリースビルドは、各<code>cli/v*</code>リリースに<code>SHA256SUMS</code>ファイルと一緒に添付されています。<code>FLICK_URL</code>には、利用するインスタンスのURLを設定してください。</p>

<h2 id="self-host">{t().guides.sections.selfHost}</h2>
<p>Flickは、自分で管理する小さなマシンで動かせるように作られています。構成は、Webフロントエンド（ビルドしたSvelteKitアプリを配信するnginx）、Go API、Goのクリーンアップワーカー、NATS JetStream、PostgreSQL 17です。Valkeyは任意ですが、リアルタイム転送には必要です。S3互換バケットも任意です。バケットがない場合、ファイルはデータベースに収まる1 MiBまでに制限されます。</p>
<p>イメージは<code>docker.io/haradwaith/flick-api</code>、<code>flick-worker</code>、<code>flick-web</code>として公開され、バージョンまたはコミットのタグが付いています（<code>latest</code>タグはありません）。ソースからビルドすることもできます。</p>
<p>リポジトリには、<code>deploy/base</code>のKubernetesマニフェストと、k3sクラスター（<code>docs/runbook/k3s-base.md</code>）とOCI Always Freeリソース（<code>docs/runbook/oci-free-tier.md</code>）向けの手順書が含まれています。すべての設定は<code>.env.example</code>と<code>docs/architecture/env-contract.md</code>に記載されています。</p>
