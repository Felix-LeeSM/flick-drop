<h2 id="privacy">{t().guides.sections.privacy}</h2>
<p>内容は公開のファイル暗号化形式である<a href="https://age-encryption.org/">age</a>を用い、ブラウザ内で暗号化されます。送信ごとに新しい耐量子ハイブリッド鍵（ML-KEM-768とX25519）を生成します。大きなファイルは64 KiBのチャンクに分割して暗号化し、最後のチャンクの検証が終わるまで内容は表示されません。</p>
<p>パスワードを設定しない場合、リンクの鍵はURLフラグメント（<code>#key=AGE-SECRET-KEY-PQ-1…</code>）に入ります。ブラウザはフラグメントをサーバーへ送信しないため、HTTPリクエストやアクセスログに鍵が記録されることはありません。</p>
<p>パスワードを設定すると、鍵をageのscryptモード（work factor 18）でラップし、ラップ済みの鍵だけをアップロードします。あわせてパスワードから別のアクセス証明（PBKDF2-SHA-256、600,000回反復）を導出し、サーバーはその証明のハッシュだけを保持して内容の引き渡し前に照合します。データベースのコピーを入手した攻撃者は、ラップ済みの鍵に対してオフラインでパスワード推測を試せるため、十分に長いパスワードを使ってください。内蔵の生成機能は80ビットのパスワードを作成します。</p>
<p>サーバーには、配信ID、暗号化済みバイト列、サイズ、ファイル種別、暗号化済みファイル名、タイムスタンプ、パスワードの誤入力回数が保存されます。IPアドレスは保存しません。Webのアクセスログでは配信IDを<code>&lt;id&gt;</code>にマスクし、クライアントIP、リファラー、クエリ文字列を記録しません。</p>
<p>リアルタイム転送の仕組みは異なります。受け取る側のブラウザが1回限りの鍵ペアを生成して公開鍵だけを送り、送る側がその公開鍵で暗号化します。サーバーは暗号文をメモリ上で中継するだけで、コードのハッシュや端末の表示名などの待機情報は、永続化されないキャッシュに短時間だけ保持されます。</p>
<aside>
	<p><strong>Web暗号化の限界：</strong>ブラウザで暗号化する以上、サーバーが配信するJavaScriptを信頼する必要があります。悪意あるサーバーは鍵やパスワードを盗むコードを配信でき、リアルタイム転送でも自身の鍵にすり替えられます。この設計はデータベース・ログ・バックアップの流出を防ぎますが、運営者自身の悪意までは防げません。<code>SHA256SUMS</code>で検証したコマンドラインクライアントを使えば、配信されるJavaScriptへの信頼は不要になります。</p>
</aside>

<h2 id="source">{t().guides.sections.source}</h2>
<p>FlickはApache 2.0ライセンスのオープンソースです。リポジトリは<a href={repo}>github.com/Felix-LeeSM/flick-drop</a>にあり、まず次の箇所を読むと全体像がつかめます。</p>
<ul>
	<li><code>web/src/lib/crypto/</code>：ブラウザでの暗号化、リンク鍵、パスワードのアクセス証明</li>
	<li><code>contracts/age-format-v1.md</code>：暗号化フォーマットと各API呼び出しの仕様</li>
	<li><code>docs/architecture/security-model.md</code>：対象外とした脅威を含む脅威モデル全体</li>
	<li><code>cmd/flick</code>：ブラウザと同じ方式で暗号化するコマンドラインクライアント</li>
</ul>
<p>コマンドラインクライアントを使うと、ターミナルから直接送信・開封できます。</p>
<pre><code>go install github.com/Felix-LeeSM/flick-drop/cmd/flick@latest
flick send -ttl 1h -file report.pdf
flick open 'https://flick.example/s/…#key=…'</code></pre>
<p>macOS、Linux、Windows向けのビルドと<code>SHA256SUMS</code>ファイルは、各<code>cli/v*</code>リリースに添付されています。利用するインスタンスのURLを<code>FLICK_URL</code>に設定してください。</p>

<h2 id="self-host">{t().guides.sections.selfHost}</h2>
<p>Flickは自前で管理する小規模なマシンで動かせるように設計されています。構成要素は、Webフロントエンド（ビルド済みSvelteKitアプリを配信するnginx）、Go API、Goクリーンアップワーカー、NATS JetStream、PostgreSQL 17です。Valkeyは任意ですが、リアルタイム転送を有効にする場合は必須です。S3互換バケットも任意で、使わない場合はデータベースに格納できる1 MiBがファイルサイズの上限になります。</p>
<p>コンテナイメージは<code>docker.io/haradwaith/flick-api</code>、<code>flick-worker</code>、<code>flick-web</code>として公開されており、バージョンまたはコミットのタグが付きます（<code>latest</code>タグはありません）。ソースからのビルドも可能です。</p>
<p>リポジトリ内の<code>deploy/base</code>にKubernetesマニフェストがあり、k3sクラスター向け（<code>docs/runbook/k3s-base.md</code>）とOCI Always Freeリソース向け（<code>docs/runbook/oci-free-tier.md</code>）の手順書を用意しています。すべての設定項目は<code>.env.example</code>と<code>docs/architecture/env-contract.md</code>に一覧があります。</p>
