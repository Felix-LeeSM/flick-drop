"""Regenerates title-kr.css and files/ from MaruBuri-SemiBold.ttf (npm @kfonts/maruburi, OFL-1.1).

The subsets are renamed "Flick Title KR": OFL forbids a modified font from using a Reserved Font Name.

Usage: python3 subset.py <MaruBuri-SemiBold.ttf> <unicode.json from npm @fontsource-variable/noto-serif-kr>
Needs: pip install fonttools brotli
"""

import json
import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

here = pathlib.Path(__file__).parent
source, ranges_path = sys.argv[1], sys.argv[2]
cmap = set(TTFont(source).getBestCmap())
out = here / "files"
out.mkdir(exist_ok=True)
for old in out.glob("*.woff2"):
    old.unlink()


def codepoints(spec):
    for part in spec.split(","):
        lo, _, hi = part.strip().removeprefix("U+").partition("-")
        yield from range(int(lo, 16), int(hi or lo, 16) + 1)


faces = []
for key, spec in json.loads(pathlib.Path(ranges_path).read_text()).items():
    wanted = [cp for cp in codepoints(spec) if cp in cmap]
    if not wanted:
        continue
    name = f"flick-title-kr-{key.strip('[]')}.woff2"
    options = subset.Options()
    options.flavor = "woff2"
    options.hinting = False
    font = TTFont(source)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=wanted)
    subsetter.subset(font)
    for record in font["name"].names:
        if record.nameID in (1, 3, 4, 6, 16, 17, 18):
            record.string = "FlickTitleKR" if record.nameID == 6 else "Flick Title KR"
    font.save(out / name)
    faces.append(
        "@font-face {\n"
        "\tfont-family: 'Flick Title KR';\n"
        "\tfont-style: normal;\n"
        "\tfont-weight: 400;\n"
        "\tfont-display: swap;\n"
        f"\tsrc: url(./files/{name}) format('woff2');\n"
        f"\tunicode-range: {spec};\n"
        "}\n"
    )

(here / "title-kr.css").write_text(
    "/* Generated by subset.py from MaruBuri SemiBold, registered at weight 400 for serif titles. */\n"
    + "\n".join(faces)
)
print(len(faces), "faces")
